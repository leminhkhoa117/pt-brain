/**
 * One-time generator for `src/pages/atlas/atlasMuscleMap.js`.
 *
 * It joins the curated PT Brain muscle metadata (shared/muscles) to the
 * upstream Human Atlas concepts through FMA IDs, then adds name-based
 * fallbacks for the few source concepts whose FMA ID is missing or whose
 * geometry is stored under a head/part concept.
 *
 * Usage:
 *   node scripts/generate-atlas-muscle-map.mjs <somakine-pack-dir> <atlas.json>
 */
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const packDir = process.argv[2];
const atlasPath = process.argv[3];
if (!packDir || !atlasPath) {
  console.error('Usage: node scripts/generate-atlas-muscle-map.mjs <pack-dir> <atlas.json>');
  process.exit(1);
}

const { MUSCLES } = await import(
  pathToFileURL(path.resolve('..', 'shared', 'muscles', 'index.js')).href
);
const pack = JSON.parse(fs.readFileSync(path.resolve(packDir, 'public', 'pack.json'), 'utf8'));
const atlas = JSON.parse(fs.readFileSync(atlasPath, 'utf8'));

const extraKeywords = {
  quadriceps: [
    'quadriceps',
    'rectus femoris',
    'vastus lateralis',
    'vastus medialis',
    'vastus intermedius',
  ],
  'erector-spinae': ['iliocostalis', 'longissimus', 'spinalis'],
  'finger-flexors': ['flexor digitorum superficialis', 'flexor digitorum profundus'],
  'pectoralis-major': ['pectoralis major'],
  'biceps-brachii': ['biceps brachii'],
  'triceps-brachii': ['triceps brachii'],
  'biceps-femoris': ['biceps femoris'],
  gastrocnemius: ['gastrocnemius'],
  deltoid: ['deltoid'],
  trapezius: ['trapezius'],
  'levator-scapulae': ['levator scapulae'],
  'gluteus-maximus': ['gluteus maximus'],
  'gluteus-medius': ['gluteus medius'],
  'gluteus-minimus': ['gluteus minimus'],
  'adductor-longus': ['adductor longus'],
  'adductor-brevis': ['adductor brevis'],
  'adductor-magnus': ['adductor magnus'],
  'rectus-abdominis': ['rectus abdominis'],
  'transversus-abdominis': ['transversus abdominis'],
  'internal-oblique': ['internal oblique'],
  'latissimus-dorsi': ['latissimus dorsi'],
  multifidus: ['multifidus'],
  'tibialis-anterior': ['tibialis anterior'],
  'tibialis-posterior': ['tibialis posterior'],
};

const conceptsBySlug = {};
const conceptToSlug = {};
const keywordRows = [];

for (const [slug, item] of Object.entries(MUSCLES)) {
  const structure = pack.structures.find(
    (candidate) => candidate.id === `somakine:structure:${slug}`,
  );
  const fmaIds = Object.entries(structure?.externalIds ?? {})
    .filter(([key]) => key === 'fma' || key.startsWith('fma:'))
    .map(([, value]) => value);

  const concepts = atlas.concepts.filter((concept) => fmaIds.includes(concept.id));
  conceptsBySlug[slug] = concepts.map((concept) => concept.id);
  for (const concept of concepts) conceptToSlug[concept.id] = slug;

  const keywords = [item.en.toLowerCase(), ...(extraKeywords[slug] ?? [])]
    .map((keyword) => keyword.toLowerCase().trim())
    .filter(Boolean);

  keywordRows.push({ slug, keywords: [...new Set(keywords)] });
}

keywordRows.sort((a, b) => {
  const longestA = Math.max(...a.keywords.map((keyword) => keyword.length));
  const longestB = Math.max(...b.keywords.map((keyword) => keyword.length));
  return longestB - longestA || a.slug.localeCompare(b.slug);
});

const source = `/**
 * Generated by scripts/generate-atlas-muscle-map.mjs.
 * FMA joins keep the curated PT Brain metadata attached to the exact
 * upstream concepts; keyword fallbacks cover head/part concepts.
 */
export const ATLAS_MUSCLE_CONCEPTS = ${JSON.stringify(conceptsBySlug, null, 2)};

export const CONCEPT_TO_MUSCLE = ${JSON.stringify(conceptToSlug, null, 2)};

export const ATLAS_MUSCLE_KEYWORDS = ${JSON.stringify(keywordRows, null, 2)};
`;

const outPath = path.resolve('src', 'pages', 'atlas', 'atlasMuscleMap.js');
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, source);
console.log(
  `Wrote ${Object.keys(conceptsBySlug).length} muscles, ${Object.keys(conceptToSlug).length} concept links, ${keywordRows.length} keyword rows to ${outPath}`,
);
